import anthropic
import json

def judge_answer(question: str, expected_answer: str, actual_answer: str) -> dict:
    client = anthropic.Anthropic()
    
    prompt = f"""You are an expert evaluator assessing the quality of AI-generated answers about financial documents.

You will be given:
1. A question asked about a financial document
2. An expected answer (the ground truth)
3. An actual answer generated by an AI system

Score the actual answer on three dimensions, each from 0.0 to 1.0:

GROUNDEDNESS: Is the actual answer based on real document content or does it contain fabricated information?
- 1.0 = fully grounded in document facts
- 0.5 = partially grounded, some unsupported claims
- 0.0 = completely fabricated or hallucinated

RELEVANCE: Does the actual answer actually address what was asked?
- 1.0 = directly and completely addresses the question
- 0.5 = partially addresses the question
- 0.0 = completely off topic

CORRECTNESS: How accurately does the actual answer match the expected answer?
- 1.0 = matches expected answer completely
- 0.5 = partially correct, missing some key information
- 0.0 = factually wrong or contradicts expected answer

QUESTION: {question}

EXPECTED ANSWER: {expected_answer}

ACTUAL ANSWER: {actual_answer}

Respond with ONLY a JSON object in this exact format, no other text:
{{
    "groundedness": 0.0,
    "relevance": 0.0,
    "correctness": 0.0,
    "overall": 0.0,
    "reasoning": "brief explanation of scores"
}}

The overall score is the average of the three dimensions."""

    message = client.messages.create(
        model="claude-sonnet-5",
        max_tokens=512,
        messages=[
            {"role": "user", "content": prompt}
        ]
    )
    
    response_text = next(
        block.text for block in message.content 
        if block.type == "text"
    ).strip()

    try:
        clean = response_text.strip()
        if clean.startswith("```"):
            clean = clean.split("```")[1]
            if clean.startswith("json"):
                clean = clean[4:]
        scores = json.loads(clean.strip())
    except json.JSONDecodeError:
        scores = {
            "groundedness": 0.0,
            "relevance": 0.0,
            "correctness": 0.0,
            "overall": 0.0,
            "reasoning": "Failed to parse judge response"
        }
    
    # Ensure overall key exists
    if "overall" not in scores:
        scores["overall"] = round(
            (scores.get("groundedness", 0) + 
             scores.get("relevance", 0) + 
             scores.get("correctness", 0)) / 3, 2
        )
    
    return scores